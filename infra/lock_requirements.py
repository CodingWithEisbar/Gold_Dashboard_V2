"""Freeze installed dependency closures, including hashes, without bundling QA tools into runtime."""
import json
import urllib.request
from importlib import metadata
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
RUNTIME = ["fastapi", "uvicorn", "pydantic-settings", "sqlalchemy", "alembic", "psycopg", "psycopg-binary", "httpx", "tzdata"]
DEV = ["pytest", "hypothesis", "ruff", "pip-audit"]


def closure(roots):
    pending = [Requirement(root) for root in roots]
    result = {}
    processed = set()
    environment = default_environment()
    while pending:
        requested = pending.pop()
        name = canonicalize_name(requested.name)
        key = (name, tuple(sorted(requested.extras)))
        if key in processed:
            continue
        processed.add(key)
        distribution = metadata.distribution(name)
        result[name] = distribution.version
        for value in distribution.requires or []:
            requirement = Requirement(value)
            if requirement.marker is None or any(requirement.marker.evaluate({**environment, "extra": extra})
                                                  for extra in ("", *requested.extras)):
                pending.append(requirement)
    return result


def main():
    for target, roots in [("requirements.lock", RUNTIME), ("requirements-dev.lock", RUNTIME + DEV)]:
        lines = ["# Resolved 2026-11-06. Generated by infra/lock_requirements.py; all release hashes from PyPI."]
        for name, version in sorted(closure(roots).items()):
            # Only installed package metadata determines this fixed PyPI endpoint, never application input.
            with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=20) as response:
                document = json.load(response)
            hashes = sorted({file["digests"]["sha256"] for file in document["urls"]})
            if not hashes:
                raise RuntimeError(f"Missing release hashes: {name}")
            lines.append(f"{name}=={version} \\")
            lines.extend(f"    --hash=sha256:{digest}" + (" \\" if i < len(hashes) - 1 else "")
                         for i, digest in enumerate(hashes))
        (ROOT / "backend" / target).write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
