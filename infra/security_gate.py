"""Run the Linux container security gate in an isolated Compose project.

Never uses production credentials, publishes only a loopback port, and retains failed scans.
No scan ignores or risk acceptance are generated by this runner.
"""

import argparse
import json
import os
import secrets
import shutil
import subprocess
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATE = ROOT / ".tools" / "security-gate"
REPORTS = ROOT / "artifacts" / "security-gate"
PROJECT = "gold-security-gate"
IMAGES = {name: f"gold-{name}:gate" for name in ("backend", "frontend", "postgres", "backup")}


def run(arguments, *, report=None, check=True):
    result = subprocess.run(
        arguments,
        cwd=ROOT,
        text=True,
        encoding="utf-8",
        errors="replace",
        stdout=subprocess.PIPE if report else None,
        stderr=subprocess.STDOUT if report else None,
    )
    if report:
        (REPORTS / report).write_text(result.stdout, encoding="utf-8")
    if check and result.returncode:
        raise SystemExit(f"Command failed (exit {result.returncode}); inspect {report or 'output above'}")
    return result


def prepare():
    STATE.mkdir(parents=True, exist_ok=True)
    REPORTS.mkdir(parents=True, exist_ok=True)
    secret_file = STATE / ".env"
    entries = {}
    private_dir = STATE / "secrets"
    private_dir.mkdir(mode=0o700, exist_ok=True)
    for name in ("DB_ADMIN_PASSWORD", "DB_OWNER_PASSWORD", "DB_READER_PASSWORD", "DB_INGESTOR_PASSWORD"):
        path = private_dir / name.lower()
        if not path.exists():
            with path.open("x", encoding="utf-8") as stream:
                stream.write(secrets.token_urlsafe(36))
            path.chmod(0o444)
        entries[name + "_FILE"] = path.as_posix()
    entries.update(
        APP_ENV="production",
        BACKEND_IMAGE=IMAGES["backend"],
        FRONTEND_IMAGE=IMAGES["frontend"],
        POSTGRES_IMAGE=IMAGES["postgres"],
        METALS_LICENSE_CONFIRMED="false",
        XAU_API_KEY="",
    )
    secret_file.write_text(
        "\n".join(f"{key}={value}" for key, value in entries.items()) + "\n", encoding="utf-8"
    )
    secret_file.chmod(0o600)
    (STATE / "compose.gate.yaml").write_text(
        'services:\n  frontend:\n    ports: ["127.0.0.1:18080:8080"]\n', encoding="utf-8"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("phase", choices=("prepare", "build", "start", "scan", "test", "stop"))
    parser.add_argument("--docker", default=os.environ.get("DOCKER_BINARY", shutil.which("docker")))
    args = parser.parse_args()
    if not args.docker:
        parser.error("Docker CLI required; set --docker or DOCKER_BINARY")
    prepare()
    docker = args.docker
    compose = [
        docker,
        "compose",
        "--project-name",
        PROJECT,
        "--env-file",
        str(STATE / ".env"),
        "-f",
        str(ROOT / "compose.yaml"),
        "-f",
        str(STATE / "compose.gate.yaml"),
    ]
    if args.phase == "prepare":
        run(compose + ["config", "--quiet"])
        run([docker, "version", "--format", "{{json .Server}}"], report="docker-server.json")
    elif args.phase == "build":
        run(compose + ["build", "--pull"])
        run([docker, "build", "--pull", "-t", IMAGES["backup"], "-f", "infra/backup/Dockerfile", "."])
        for name, image in IMAGES.items():
            run([docker, "image", "inspect", image], report=f"{name}-image.json")
    elif args.phase == "start":
        run(compose + ["up", "-d", "--force-recreate", "--wait", "--wait-timeout", "180"])
        run(compose + ["ps", "--format", "json"], report="compose-ps.json")
    elif args.phase == "test":
        run([docker, "build", "-t", "gold-verifier:gate", "-f", "infra/testing/Dockerfile", "."])
        uid, gid = 10002, 10002
        if os.name == "posix" and os.getuid() != 0:
            # Bind-mounted reports belong to the host runner, including existing JUnit files.
            # Match its identity on Linux; keep the image's non-root identity on Windows.
            uid, gid = os.getuid(), os.getgid()
        run(
            [
                docker,
                "run",
                "--rm",
                "--user",
                f"{uid}:{gid}",
                "--read-only",
                "--cap-drop",
                "ALL",
                "--security-opt",
                "no-new-privileges:true",
                "--pids-limit",
                "128",
                "--memory",
                "1g",
                "--cpus",
                "2",
                "--network",
                PROJECT + "_database",
                "--tmpfs",
                f"/tmp:uid={uid},gid={gid}",  # noqa: S108 -- private container tmpfs, not a host temp file
                "--env",
                "HYPOTHESIS_STORAGE_DIRECTORY=/tmp/hypothesis",
                "--mount",
                f"type=bind,source={ROOT},target=/workspace,readonly",
                "--mount",
                f"type=bind,source={REPORTS},target=/reports",
                "--mount",
                f"type=bind,source={STATE / 'secrets/db_admin_password'},target=/run/secrets/db_admin_password,readonly",
                "gold-verifier:gate",
            ]
        )
    elif args.phase == "scan":
        trivy = ROOT / ".tools" / "security" / ("trivy.exe" if os.name == "nt" else "trivy")
        context = run(
            [docker, "context", "inspect", "--format", "{{.Endpoints.docker.Host}}"],
            report="docker-endpoint.txt",
        )
        os.environ["DOCKER_HOST"] = context.stdout.strip()
        results = []
        for name, image in IMAGES.items():
            report = REPORTS / f"{name}-scan.json"
            completed = run(
                [
                    str(trivy),
                    "image",
                    "--image-src",
                    "docker",
                    "--cache-dir",
                    str(ROOT / ".tools/trivy-cache"),
                    "--scanners",
                    "vuln",
                    "--format",
                    "json",
                    "--output",
                    str(report),
                    "--exit-code",
                    "1",
                    "--severity",
                    "HIGH,CRITICAL",
                    image,
                ],
                check=False,
            )
            sbom = run(
                [
                    str(trivy),
                    "image",
                    "--image-src",
                    "docker",
                    "--cache-dir",
                    str(ROOT / ".tools/trivy-cache"),
                    "--format",
                    "cyclonedx",
                    "--output",
                    str(REPORTS / f"{name}-sbom.json"),
                    image,
                ],
                check=False,
            )
            results.append(
                {"image": image, "exit_code": completed.returncode, "sbom_exit_code": sbom.returncode}
            )
        (REPORTS / "scan-summary.json").write_text(
            json.dumps(
                {
                    "checked_at": datetime.now(UTC).isoformat(),
                    "passed": all(item["exit_code"] == 0 and item["sbom_exit_code"] == 0 for item in results),
                    "images": results,
                },
                indent=2,
            ),
            encoding="utf-8",
        )
        if any(item["exit_code"] or item["sbom_exit_code"] for item in results):
            raise SystemExit("Final image gate failed; raw findings retained")
    elif args.phase == "stop":
        run(compose + ["down"])
        print("Stopped only the gold-security-gate project; retained test volume and reports")


if __name__ == "__main__":
    main()
